hubs = json.load(open(sys.argv[2]))
npcs = json.load(open(sys.argv[3]))
dbc = sys.argv[4]
heights = json.load(open(sys.argv[5]))   # from the 'z' pass
givers = json.load(open(sys.argv[6])) if len(sys.argv) > 6 else []   # hub_givers.json (quest givers and quest levels)

def core_range(hub, lo, hi):
    """the hub's core level range: median quest level of the quests given within 150 yards, +-5,
    inside the 15-85th percentile range (Rut'theran Village's 10-56 came from a few late quests)"""
    levels = sorted({(int(g[6]), int(g[7])) for g in givers if int(g[0]) == hub['map'] and math.hypot(g[1] - hub['x'], g[2] - hub['y']) < 150})
    levels = sorted(l for q, l in levels)
    if not levels:
        return lo, hi
    med = levels[len(levels) // 2]
    return max(lo, med - 5), min(hi, med + 5)


def load(f):
    d = open(f, 'rb').read(); _, n, fc, rs, ss = struct.unpack('<4s4I', d[:20])
    return [struct.unpack('<%dI' % fc, d[20 + i * rs:20 + (i + 1) * rs]) for i in range(n)]
ft = {f[0]: f for f in load(dbc + '/FactionTemplate.dbc')}

def friendly(faction, side):
    f = ft.get(faction)
    if not f:
        return False
    our, friend, enemy = f[3], f[4], f[5]
    a = 2; h = 4
    if side == 'A':
        return not (enemy & a) and bool((friend & a) or (our & a) or (not friend and not our))
    if side == 'H':
        return not (enemy & h) and bool((friend & h) or (our & h) or (not friend and not our))
    return not (enemy & a) and not (enemy & h)

def nearest(hub, flag, side):
    best = None
    for guid, entry, name, faction, flags, m, x, y, z in npcs:
        if m != hub['map'] or not (flags & flag) or not friendly(faction, side):
            continue
        d = math.hypot(x - hub['x'], y - hub['y'])
        if d <= 600 and (best is None or d < best[0]):
            best = (d, guid, x, y, z, name)
    return best

